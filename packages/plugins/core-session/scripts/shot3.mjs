import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
await page.goto('http://127.0.0.1:12001', { waitUntil: 'networkidle' })
await page.getByText('认证设置').click()
await page.waitForTimeout(800)
console.log('--- h2:', await page.locator('h2').textContent().catch(() => ''))
console.log('--- textarea:', await page.locator('textarea').count())
console.log('--- save btn:', await page.getByRole('button', { name: '保存' }).count())
console.log('--- invalid save → error?')
await page.getByRole('button', { name: '保存' }).click()
await page.waitForTimeout(400)
console.log('--- error text:', (await page.locator('p.text-destructive').textContent().catch(() => '')) || '(none)')
await browser.close()

import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
page.on('console', (m) => { if (m.type() === 'error') console.log('[console.error]', m.text().slice(0, 300)) })
page.on('response', (r) => { if (r.status() >= 400) console.log('[http ' + r.status() + ']', r.url().slice(0, 120)) })
await page.goto('http://127.0.0.1:12001', { waitUntil: 'networkidle' })
await page.waitForTimeout(3000)
console.log('--- article count:', await page.locator('article').count())
console.log('--- h1:', await page.locator('h1').textContent().catch(() => ''))
const text = await page.evaluate(() => document.body.innerText.slice(0, 500))
console.log('--- body head:', text.replace(/\n+/g, ' | '))
const overlay = await page.locator('vite-error-overlay, #vite-error-overlay').count()
console.log('--- vite overlay:', overlay)
if (overlay) console.log('--- overlay text:', await page.locator('vite-error-overlay').textContent().catch(() => ''))
await browser.close()
